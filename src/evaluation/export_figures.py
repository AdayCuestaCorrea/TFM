RESIDUAL_MODELS = ["xgboost_alone", "hybrid", "ensemble_equal"]
IMPORTANCE_MODELS = ["xgboost_residual", "xgboost_alone"]


def assert_theme_applied(fig: go.Figure, filename: str) -> None:
    """Verify the figure carries the shared VIU template before it is written.

    The whole point of the theme module is that the notebook's figures and the memoria's
    PNGs cannot look different. That guarantee is only real if it is checked: a builder
    that forgot `apply_theme`, or a second palette defined elsewhere, would otherwise
    produce a silently off-brand PNG that nobody notices until the defense.
    """
    colorway = fig.layout.template.layout.colorway
    if colorway != theme_fingerprint():
        raise ValueError(
            f"{filename}: figure does not carry the shared VIU template.\n"
            f"  expected colorway: {theme_fingerprint()}\n"
            f"  found:             {colorway}\n"
            "  Every builder in dashboard_figures.py must return apply_theme(fig)."
        )


def export(fig: go.Figure, filename: str, width: int = 1100, height: int = 600) -> Path:
    """Write one figure and return its path."""
    assert_theme_applied(fig, filename)
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    path = FIGURES_DIR / filename
    fig.write_image(path, width=width, height=height, scale=EXPORT_SCALE)
    print(f"  exported: {filename}", flush=True)
    return path


