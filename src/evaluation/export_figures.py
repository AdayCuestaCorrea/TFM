"""Export every dashboard figure to reports/figures/ as static PNG.

Run as a standalone script, NOT from inside the notebook:

    python -m src.evaluation.export_figures

Why separate. kaleido 1.x drives a headless Chrome subprocess. Called repeatedly from a
Jupyter kernel it deadlocks -- observed here: the first two exports succeeded, then the
kernel blocked indefinitely at near-zero CPU with no error. In a plain sequential process
the same calls complete without issue. Keeping export out of the notebook also means
executing the notebook stays fast and side-effect-free, and the memoria's figures are
regenerated by one deterministic command.

The figures themselves come from dashboard_figures.py, the same builders the notebook
renders interactively, so the PNGs and the live dashboard cannot drift apart.
"""

